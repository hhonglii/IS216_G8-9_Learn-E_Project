/* ══════════════════════════════════════════════════════════════════
 *  Learn-E — ClassroomGame schema
 *  One Boss Battle per classroom. The template (rules, scoring, visuals) is
 *  fixed in code; the professor chooses the boss and hearts and writes the
 *  questions. Drafts may be incomplete, and publishing checks the stored draft
 *  (utils/classroomGameDraft.js). version counts publications, so results and
 *  "boss defeated" only ever describe the questions currently published.
 * ══════════════════════════════════════════════════════════════════
 */
import mongoose from "mongoose";
const { Schema } = mongoose;

// Ids are generated by the editor, so autosave never has to swap them mid-edit.
const optionSchema = new Schema(
  {
    id: { type: String, required: true },
    label: { type: String, default: "" },
  },
  { _id: false, id: false },
);

const questionSchema = new Schema(
  {
    id: { type: String, required: true },
    code: { type: String, default: "" },
    prompt: { type: String, default: "" },
    options: [optionSchema],
    correctOptionId: { type: String, default: "" },
    explanation: { type: String, default: "" },
    keepOrder: { type: Boolean, default: false },
    // A generated question stays true until the professor approves it.
    needsReview: { type: Boolean, default: false },
  },
  { _id: false, id: false },
);

const schema = new Schema(
  {
    classroomId: {
      type: Schema.Types.ObjectId,
      ref: "Classroom",
      required: true,
      unique: true,
    },
    title: { type: String, default: "" },
    bossId: { type: String, required: true },
    hearts: { type: Number, min: 1, max: 10, default: 3 },
    questions: [questionSchema],
    status: { type: String, enum: ["draft", "published"], default: "draft" },
    version: { type: Number, default: 0, min: 0 },
    createdBy: { type: Schema.Types.ObjectId, ref: "User", required: true },
  },
  { timestamps: true, optimisticConcurrency: true },
);

export default mongoose.models.ClassroomGame ||
  mongoose.model("ClassroomGame", schema);
